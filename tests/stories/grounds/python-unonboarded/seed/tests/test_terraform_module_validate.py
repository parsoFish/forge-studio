"""
Integration tests: rendered terraform-module Copier template passes Terraform CLI gates.

Tests verify that files generated by 'copier copy modules/terraform-module <dst>'
pass all mandatory Terraform quality checks without requiring cloud credentials:

  - terraform fmt -check exits 0 (generated HCL is properly formatted)
  - terraform init -backend=false exits 0 (required_providers block is valid)
  - terraform validate exits 0 (configuration is syntactically and semantically correct)
  - terraform validate outputs a Success message

Prerequisites (tests are skipped automatically when either is missing):
  - copier CLI available in PATH
  - terraform CLI available in PATH

All tests fail until modules/terraform-module/ contains a valid, working Copier template.
"""

import os
import subprocess
import tempfile
import unittest


REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TEMPLATE_DIR = os.path.join(REPO_ROOT, "modules", "terraform-module")

# Inputs used for all validation tests.  The null provider requires no credentials,
# making it suitable for CI environments without cloud access.
KNOWN_INPUTS = {
    "module_name": "integration_test_module",
    "description": "Integration test module for Terraform CLI validation",
    "author": "ci_test",
    "required_providers": "hashicorp/null:~> 3.0",
}


# ---------------------------------------------------------------------------
# Availability guards
# ---------------------------------------------------------------------------


def _copier_available() -> bool:
    """Return True if the copier CLI is on the PATH and responds to --version."""
    try:
        result = subprocess.run(
            ["copier", "--version"],
            capture_output=True,
            timeout=15,
        )
        return result.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def _terraform_available() -> bool:
    """Return True if the terraform CLI is on the PATH and responds to 'version'."""
    try:
        result = subprocess.run(
            ["terraform", "version"],
            capture_output=True,
            timeout=15,
        )
        return result.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def _both_tools_available() -> bool:
    """Return True only when both copier and terraform CLIs are available."""
    return _copier_available() and _terraform_available()


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _render_template(dst_dir: str) -> subprocess.CompletedProcess:
    """
    Render the terraform-module template to dst_dir with KNOWN_INPUTS.

    --overwrite avoids prompts if the directory already has content.
    --defaults fills unspecified questions with their template defaults.
    """
    cmd = [
        "copier", "copy",
        "--overwrite",
        "--defaults",
    ]
    for key, value in KNOWN_INPUTS.items():
        cmd.extend(["--data", f"{key}={value}"])
    cmd.extend([TEMPLATE_DIR, dst_dir])
    return subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        timeout=60,
    )


def _run(args: list, cwd: str, timeout: int = 60) -> subprocess.CompletedProcess:
    """Run a subprocess in the given working directory and return the completed process."""
    return subprocess.run(
        args,
        capture_output=True,
        text=True,
        cwd=cwd,
        timeout=timeout,
    )


def _terraform_init(cwd: str) -> subprocess.CompletedProcess:
    """
    Run 'terraform init -backend=false' in the given directory.

    -backend=false downloads provider plugins without configuring remote state —
    appropriate for CI environments that only need to validate HCL correctness.
    """
    return _run(
        ["terraform", "init", "-backend=false", "-no-color"],
        cwd=cwd,
        timeout=180,
    )


# ---------------------------------------------------------------------------
# terraform fmt -check
# ---------------------------------------------------------------------------


@unittest.skipUnless(
    _both_tools_available(),
    "copier and/or terraform CLI not available — skipping fmt tests",
)
class TestTerraformModuleGeneratedFormat(unittest.TestCase):
    """
    Generated Terraform files must pass 'terraform fmt -check'.

    The template is responsible for emitting properly formatted HCL.
    Formatting failures here must be fixed in the template source, not by
    having callers run 'terraform fmt' after generation.
    """

    @classmethod
    def setUpClass(cls):
        """Render the template once; all fmt tests share the output directory."""
        cls._tmp = tempfile.TemporaryDirectory()
        cls.output_dir = cls._tmp.name
        cls.render_result = _render_template(cls.output_dir)

    @classmethod
    def tearDownClass(cls):
        cls._tmp.cleanup()

    def test_template_renders_successfully_before_fmt_check(self):
        """
        'copier copy' must exit 0 before fmt checks can run.

        A render failure means the template itself is broken, not the formatting.
        """
        self.assertEqual(
            self.render_result.returncode,
            0,
            "copier copy failed — fmt tests cannot proceed:\n"
            f"STDOUT:\n{self.render_result.stdout}\n"
            f"STDERR:\n{self.render_result.stderr}",
        )

    def test_terraform_fmt_check_passes_for_generated_module_root(self):
        """
        'terraform fmt -check -recursive .' must exit 0 on the generated module root.

        Callers of 'copier copy' must receive pre-formatted HCL they can commit
        directly without running a formatter pass.
        """
        result = _run(
            ["terraform", "fmt", "-check", "-recursive", "-no-color", "."],
            cwd=self.output_dir,
        )
        self.assertEqual(
            result.returncode,
            0,
            "terraform fmt -check failed on the generated module. "
            "The template must emit properly formatted HCL.\n"
            f"Files needing formatting:\n{result.stdout}\n"
            f"Errors:\n{result.stderr}",
        )

    def test_terraform_fmt_check_passes_for_generated_examples_directory(self):
        """
        'terraform fmt -check' must also pass for examples/complete/main.tf.

        The examples are part of the module's public surface and must be
        formatted to the same standard as the module root.
        """
        examples_dir = os.path.join(self.output_dir, "examples")
        if not os.path.isdir(examples_dir):
            self.skipTest(
                "examples/ directory was not generated — "
                "test will apply once the template generates examples/"
            )
        result = _run(
            ["terraform", "fmt", "-check", "-recursive", "-no-color", "."],
            cwd=examples_dir,
        )
        self.assertEqual(
            result.returncode,
            0,
            "terraform fmt -check failed in the generated examples/ directory.\n"
            f"Files needing formatting:\n{result.stdout}\n"
            f"Errors:\n{result.stderr}",
        )


