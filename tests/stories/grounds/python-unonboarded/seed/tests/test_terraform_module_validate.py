class TestTerraformModuleGeneratedInit(unittest.TestCase):
    """
    'terraform init -backend=false' must succeed on the generated module,
    confirming the required_providers block is syntactically valid and the
    provider sources are resolvable from the public Terraform registry.

    A failure here typically means the provider source or version constraint
    rendered by the template is malformed.
    """

    @classmethod
    def setUpClass(cls):
        cls._tmp = tempfile.TemporaryDirectory()
        cls.output_dir = cls._tmp.name
        _render_template(cls.output_dir)

    @classmethod
    def tearDownClass(cls):
        cls._tmp.cleanup()

    def test_terraform_init_backend_false_exits_zero_for_generated_module(self):
        """
        'terraform init -backend=false' must exit 0 for the generated module.

        This validates the required_providers block the template renders from
        the 'required_providers' copier variable.
        """
        result = _terraform_init(self.output_dir)
        self.assertEqual(
            result.returncode,
            0,
            "terraform init -backend=false failed on the generated module:\n"
            f"STDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}",
        )


# ---------------------------------------------------------------------------
# terraform validate
# ---------------------------------------------------------------------------


@unittest.skipUnless(
    _both_tools_available(),
    "copier and/or terraform CLI not available — skipping validate tests",
)
class TestTerraformModuleGeneratedValidate(unittest.TestCase):
    """
    'terraform validate' must exit 0 after init on the generated module.

    This confirms the generated configuration is syntactically and semantically
    correct: no invalid resource types, no missing required arguments, no
    undeclared variables referenced in expressions.
    """

    @classmethod
    def setUpClass(cls):
        """Render the template and run init once; all validate tests share the state."""
        cls._tmp = tempfile.TemporaryDirectory()
        cls.output_dir = cls._tmp.name
        _render_template(cls.output_dir)
        # Init must succeed before validate can run; if it fails, validate tests
        # will produce meaningful failures rather than an obscure 'not initialised' error.
        _terraform_init(cls.output_dir)

    @classmethod
    def tearDownClass(cls):
        cls._tmp.cleanup()

    def test_terraform_validate_exits_zero_for_generated_module(self):
        """
        'terraform validate' must exit 0 — the generated configuration has no
        syntax errors, invalid resource types, or missing required arguments.
        """
        result = _run(
            ["terraform", "validate", "-no-color"],
            cwd=self.output_dir,
        )
        self.assertEqual(
            result.returncode,
            0,
            "terraform validate failed on the generated module:\n"
            f"STDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}",
        )

    def test_terraform_validate_reports_success_message(self):
        """
        'terraform validate' must output a 'Success' message.

        This guards against the edge case where validate exits 0 but emits
        unexpected diagnostic warnings that indicate misconfigured resources.
        """
        result = _run(
            ["terraform", "validate", "-no-color"],
            cwd=self.output_dir,
        )
        combined = result.stdout + result.stderr
        self.assertIn(
            "Success",
            combined,
            "terraform validate did not output a Success message despite exit code 0:\n"
            f"STDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}",
        )

    def test_terraform_validate_reports_no_errors(self):
        """
        'terraform validate' output must not contain 'Error:' when it exits 0.

        Distinguishes a clean validation pass from a partial result where
        some resources validated but others emitted error diagnostics.
        """
        result = _run(
            ["terraform", "validate", "-no-color"],
            cwd=self.output_dir,
        )
        if result.returncode == 0:
            self.assertNotIn(
                "Error:",
                result.stdout,
                "terraform validate exited 0 but the output contains error messages:\n"
                f"STDOUT:\n{result.stdout}",
            )

    def test_terraform_validate_on_examples_complete_exits_zero(self):
        """
        'terraform validate' must also pass for examples/complete/.

        The example must be independently valid so users can run it as a
        standalone Terraform configuration to test the module.
        """
        examples_complete = os.path.join(self.output_dir, "examples", "complete")
        if not os.path.isdir(examples_complete):
            self.skipTest(
                "examples/complete/ was not generated — "
                "test will apply once the template generates that directory"
            )
        # Init examples separately (they reference the module via relative source)
        _terraform_init(examples_complete)
        result = _run(
            ["terraform", "validate", "-no-color"],
            cwd=examples_complete,
        )
        self.assertEqual(
            result.returncode,
            0,
            "terraform validate failed in examples/complete/:\n"
            f"STDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}",
        )


if __name__ == "__main__":
    unittest.main()
