#!/usr/bin/env node
/**
 * docs-gardening.mjs — this week's gardening candidates for the published
 * site, as markdown on stdout (the weekly docs-gardening workflow's input).
 *
 *   - stale: `last_verified` older than the page type's window (R22: 120 days
 *     for guides and how-tos, 180 for reference and explanation), or missing;
 *   - orphaned: a `covers:` glob that matches no tracked file, or a
 *     backticked repo path in the page body that no longer exists;
 *   - headroom: pages above 70 % of their word ceiling.
 *
 * External links are the workflow's lychee step, not this script.
 *
 * Usage: node scripts/docs-gardening.mjs [--root <dir>] [--now YYYY-MM-DD]
 * Exit: 0 report printed · 1 a page or git could not be read · 2 bad usage.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { buildReport, countWords, pageType, splitFrontmatter } from './check-docs-budget.mjs';
import { globToRegExp } from './check-test-discovery.mjs';
import { readCoversMap, SITE_PAGES } from './docs-covers.mjs';
import { isStale, windowDays } from '../apps/docs/src/freshness.mjs';

/** Backticked tokens that look like repo paths: a top-level dir we track, then a slash. */
const CITED_PATH = /`((?:packages|apps|scripts|skills|studio|tests|docs|dev)\/[A-Za-z0-9_./-]+)`/g;

/** Candidates for one site, from pages already read. Pure. */
export function gardeningCandidates({ pages, tracked, now }) {
  const stale = [];
  const orphaned = [];
  for (const p of pages) {
    const { frontmatter, body } = splitFrontmatter(p.src);
    const type = pageType(p.path, frontmatter);
    if (frontmatter.generated_from) continue; // regenerated by its story or generator, never gardened by hand
    let window;
    try {
      window = windowDays(type);
    } catch {
      window = null; // a page type with no freshness window (none today) is not judged
    }
    if (window !== null) {
      const lv = frontmatter.last_verified ? new Date(`${frontmatter.last_verified}T00:00:00Z`) : null;
      if (lv === null || Number.isNaN(lv.getTime())) stale.push({ path: p.path, why: 'no valid last_verified' });
      else if (isStale(type, lv, now)) stale.push({ path: p.path, why: `last_verified ${frontmatter.last_verified}, window ${window} days` });
    }
    for (const g of p.covers ?? []) {
      const re = globToRegExp(g);
      if (!tracked.some((t) => re.test(t))) orphaned.push({ path: p.path, why: `covers: ${g} matches no tracked file` });
    }
    const trackedSet = new Set(tracked);
    for (const m of body.matchAll(CITED_PATH)) {
      const cited = m[1].replace(/[.,:;]+$/, '');
      if (cited.includes('*') || cited.includes('<')) continue;
      if (!trackedSet.has(cited) && !tracked.some((t) => t.startsWith(`${cited.replace(/\/$/, '')}/`))) {
        orphaned.push({ path: p.path, why: `cites \`${cited}\`, which does not exist` });
      }
    }
  }
  const headroom = buildReport(
    pages.map((p) => ({ path: p.path, type: pageType(p.path, splitFrontmatter(p.src).frontmatter), words: countWords(p.src) })),
  ).over70.map((r) => ({ path: r.path, why: `${r.words}/${r.ceiling} words (${Math.round(r.pct)} %)` }));
  return { stale, orphaned, headroom };
}

export function renderReport({ stale, orphaned, headroom }, nowIso) {
  const section = (title, rows) => [`## ${title}`, '', ...(rows.length === 0 ? ['None.'] : rows.map((r) => `- \`${r.path}\` — ${r.why}`)), ''];
  return [
    `# Docs gardening candidates — ${nowIso}`,
    '',
    'For each page: verify (bump last_verified), edit, or delete.',
    '',
    ...section('Stale', stale),
    ...section('Orphaned identifiers', orphaned),
    ...section('Budget headroom (above 70 % of the ceiling)', headroom),
  ].join('\n');
}

function main(argv) {
  let root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  let now = new Date();
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--root' && argv[i + 1] !== undefined) root = resolve(argv[++i]);
    else if (argv[i] === '--now' && /^\d{4}-\d{2}-\d{2}$/.test(argv[i + 1] ?? '')) now = new Date(`${argv[++i]}T00:00:00Z`);
    else {
      process.stderr.write('usage: node scripts/docs-gardening.mjs [--root <dir>] [--now YYYY-MM-DD]\n');
      process.exitCode = 2;
      return;
    }
  }
  try {
    const tracked = execFileSync('git', ['-C', root, 'ls-files'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }).split('\n').filter(Boolean);
    const covers = new Map(readCoversMap(root).map((c) => [c.page, c.globs]));
    const pages = tracked
      .filter((t) => t.startsWith(`${SITE_PAGES}/`) && /\.mdx?$/.test(t) && existsSync(join(root, t)))
      .map((t) => ({ path: t, src: readFileSync(join(root, t), 'utf8'), covers: covers.get(t) ?? [] }));
    process.stdout.write(`${renderReport(gardeningCandidates({ pages, tracked, now }), now.toISOString().slice(0, 10))}\n`);
  } catch (e) {
    process.stderr.write(`docs-gardening: ${String(e.message).split('\n')[0]}\n`);
    process.exitCode = 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
