// ── R3-03-F4 helpers: real, disk-derived cross-checks ────────────────────────
// These mirror orchestrator/studio/hook-library.ts's own derivations (read
// directly off disk, no TS import from this .mjs harness) so the beats below
// assert a genuine cross-check against reality, not a re-read of whatever the
// product's own response already claims. Mirrors skills.mjs's own
// realSkillUsage/countPackageFiles pair, scanning composition.hooks instead
// of composition.skills.

function parseFrontmatter(raw) {
  const m = /^---\n([\s\S]*?)\n---/.exec(raw);
  if (!m) return null;
  try { return yaml.load(m[1]); } catch { return null; }
}

/** Which STUDIO AGENTS (SKILL.md carrying a `runtime:` block) compose
 *  `hookId` in their `composition.hooks`, sorted — mirrors
 *  computeHookUsage/deriveHookUsage in orchestrator/studio/hook-library.ts. */
function realHookUsage(hookId) {
  const skillsRoot = join(FORGE_ROOT, 'skills');
  const slugs = [];
  for (const entry of readdirSync(skillsRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const mdPath = join(skillsRoot, entry.name, 'SKILL.md');
    if (!existsSync(mdPath)) continue;
    let raw;
    try { raw = readFileSync(mdPath, 'utf8'); } catch { continue; }
    const data = parseFrontmatter(raw);
    if (!data || typeof data !== 'object' || !('runtime' in data)) continue; // studio agents only
    const hooks = Array.isArray(data.composition?.hooks) ? data.composition.hooks : [];
    if (hooks.includes(hookId)) slugs.push(entry.name);
  }
  return slugs.sort((a, b) => a.localeCompare(b));
}

/** Real file count under a hook's package directory — mirrors the
 *  hook.yaml + its script the detail route always returns (D-2/D-5). */
function countHookPackageFiles(id) {
  const dir = join(FORGE_ROOT, 'studio', 'hooks', id);
  let count = 0;
  const walk = (d) => {
    for (const entry of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, entry.name);
      if (entry.isDirectory()) walk(p);
      else if (entry.isFile()) count += 1;
    }
  };
  walk(dir);
  return count;
}

// ── HTML5 DataTransfer DnD helper (agent-builder catalog → drop zone) ──────
// Generic over `kind` — mirrors agents.mjs's own dragSkillChipIntoZone (kept
// LOCAL there for the same reason this is kept local here: binding is this
// journey's own concern, per the per-journey ordering comment in index.mjs).
async function dragChipIntoZone(page, id, kind) {
  const chip = page.locator(`.catalog-chip[data-id="${id}"][data-kind="${kind}"]`);
  const zone = page.locator(`[data-accepts="${kind}"]`);
  const dataTransfer = await page.evaluateHandle(() => new DataTransfer());
  await chip.dispatchEvent('dragstart', { dataTransfer });
  await zone.dispatchEvent('dragover', { dataTransfer });
  await zone.dispatchEvent('drop', { dataTransfer });
  await chip.dispatchEvent('dragend', { dataTransfer });
}

