// The agent-resolvable C8 clause (AGENTS.md or CLAUDE.md at project root) is
// classified 'agent'-tier and routes to the instructions builder; the spawn is
// suppressed (FORGE_ARCHITECT_NO_SPAWN=1), so the journey hand-writes the
// artifact a real turn would draft. checkC8 is presence + coverage (R1-04-F1):
// the hand-written AGENTS.md must EXIST and NAME the declared gate command
// (`npm test`) for the re-scan to clear — nothing under the instructions
// session's own dir needs to exist, only this project-root file.
function writeOnboardedAgentsMd(projectDir) {
  writeFileSync(join(projectDir, 'AGENTS.md'),
    '# AGENTS.md\n\n> Generated by the instructions-creator (AI-assisted, human-approved) ' +
    'for this onboarded repo.\n\n## Build & test\n\nQuality gate: `npm test`.\n\n' +
    '## Conventions\n\nNever edit tests to make them pass; fail fast at the CLI boundary.\n');
}

