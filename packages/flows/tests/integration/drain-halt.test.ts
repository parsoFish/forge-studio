/**
 * Bead forge-mfv5.1.39 (R13/R39) — a fix-loop drain whose cycle fails
 * terminally and leaves the round untouched HALTS by name; it never returns
 * the manifest to `ready-for-review` for the next 5-minute tick.
 *
 * Observed on capstone I3b round 2 (2026-10-16): every drain tick ran
 * `cycle.start` → `cycle.resume-needs-rebase` (a tracked build artifact dirty
 * in the preserved worktree) → `cycle.end` → `sendback.loop-completed` → back
 * to `ready-for-review` → re-drained, 18+ times, nothing on the verdict card.
 *
 * Fixture: real temp git (no origin, no network), the REAL `runCycle` — main
 * moved past the branch and one tracked file dirty, so the D-06 entry rebase
 * refuses before any node. The wiring is UNREACHED: a broken halt can only
 * re-run the same refused entry, never an agent (§6.16).
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { drainPendingFixWorkItems, type FixLoopDrainResult } from '../../drain-fix-loop.ts';
import type { EventLogEntry } from '@forge/kernel';
import { aggregateRun } from '../../run-model.ts';
import { runRequeue } from '../../forge-requeue.ts';
import { parseManifest } from '../../manifest.ts';
import matter from 'gray-matter';
import { deriveRoundHalt } from '../../run-model-derive-status.ts';
import type { PhaseWiring } from '../../phase-wiring.ts';
import { UNREACHED_PHASE_WIRING } from '../test-fixtures/phase-wiring.ts';
import { FIX_INIT, plantStrandedFixRound, type StrandedFixRound } from '../test-fixtures/stranded-fix-round.ts';

type Ev = { message?: string; event_type?: string; metadata?: Record<string, unknown> };

function plant(root: string, opts: { dirty: boolean }): StrandedFixRound {
  const fx = plantStrandedFixRound(root, { withGit: true, fixOrigin: 'review-fix' });
  const git = (cwd: string, args: string[]) => execFileSync('git', args, { cwd, stdio: 'pipe', encoding: 'utf8' });
  writeFileSync(join(fx.repo, 'main-moved.txt'), 'another initiative merged\n'); // main moves: the entry rebase must run
  git(fx.repo, ['add', 'main-moved.txt']);
  git(fx.repo, ['commit', '-q', '-m', 'main moved']);
  if (opts.dirty) {
    writeFileSync(join(fx.worktree, 'cost-$&-$`.txt'), 'x\n'); // a name carrying String.replace patterns
    git(fx.worktree, ['add', 'cost-$&-$`.txt']);
    git(fx.worktree, ['commit', '-q', '-m', 'feat: cost']);
    writeFileSync(join(fx.worktree, 'cost-$&-$`.txt'), 'y\n');
    writeFileSync(join(fx.worktree, 'wi-1.txt'), 'regenerated by round 1\n'); // a tracked file, uncommitted
  }
  return fx;
}

const yamlFrontmatter = (md: string): unknown => matter(md).data;
const queue = (root: string, dir: string) => join(root, '_queue', dir, `${FIX_INIT}.md`);
const events = (fx: StrandedFixRound): Ev[] =>
  readFileSync(join(fx.logDir, 'events.jsonl'), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l) as Ev);
const starts = (fx: StrandedFixRound) => events(fx).filter((e) => e.message === 'cycle.start').length;

async function drain(root: string, phaseWiring: PhaseWiring = UNREACHED_PHASE_WIRING): Promise<FixLoopDrainResult | undefined> {
  const results = await drainPendingFixWorkItems({
    queueRoot: join(root, '_queue'), logsRoot: join(root, '_logs'), phaseWiring, confirmMerge: () => false,
  });
  return results.find((r) => r.initiativeId === FIX_INIT);
}

test('a terminal entry failure halts the round: failed/ with the reason + file, a named event, never ready-for-review', async () => {
  const root = mkdtempSync(join(tmpdir(), 'drain-halt-'));
  try {
    const fx = plant(root, { dirty: true });
    const before = starts(fx);
    const r = await drain(root);
    assert.equal(r?.status, 'halted', JSON.stringify(r));
    assert.match(r?.detail ?? '', /resume-needs-rebase/);
    assert.equal(existsSync(queue(root, 'ready-for-review')), false, 'never returned to ready-for-review');
    assert.equal(existsSync(queue(root, 'in-flight')), false);
    const failed = readFileSync(queue(root, 'failed'), 'utf8');
    assert.match(failed, /^round_halt: terminal$/m, failed);
    assert.match(failed, /^round_halt_reason: ".*uncommitted changes to tracked files.*wi-1\.txt.*"$/m, 'the reason and the file list');
    const parsed = parseManifest(failed);
    assert.equal(parsed.initiative_id, FIX_INIT, 'the frontmatter survives the annotation');
    assert.match(String((yamlFrontmatter(failed) as Record<string, unknown>).round_halt_reason), /cost-\$&-\$`\.txt/, 'the reason round-trips verbatim');
    const halted = events(fx).filter((e) => e.message === 'sendback.loop-halted');
    assert.equal(halted.length, 1);
    assert.equal(halted[0]!.metadata?.classification, 'terminal');
    assert.deepEqual(halted[0]!.metadata?.pending_work_items, ['WI-6']);
    assert.equal(halted[0]!.metadata?.round, 1);
    assert.match(String(halted[0]!.metadata?.reason), /wi-1\.txt/);
    assert.equal(events(fx).some((e) => e.message === 'sendback.loop-completed'), false, 'a halted round never reads as completed');
    assert.equal(starts(fx), before + 1);

    const run = aggregateRun({ root, queueState: 'failed', manifestPath: queue(root, 'failed'), nowMs: Date.now() });
    assert.equal(run.status, 'failed', 'the surfaces read failed, never "running"');
    assert.deepEqual({ ...run.roundHalt, reason: undefined }, { round: 1, classification: 'terminal', reason: undefined });
    assert.match(run.roundHalt?.reason ?? '', /wi-1\.txt/);

    const second = await drain(root);
    assert.equal(second, undefined, 'the next tick sees nothing to drain');
    assert.equal(starts(fx), before + 1, 'no second cycle.start');
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('the same halted round re-presented to the drain is refused by name before any claim', async () => {
  const root = mkdtempSync(join(tmpdir(), 'drain-halt-refuse-'));
  try {
    const fx = plant(root, { dirty: true });
    await drain(root);
    const before = starts(fx);
    renameSync(queue(root, 'failed'), queue(root, 'ready-for-review')); // a hand move, not a Requeue
    const r = await drain(root);
    assert.equal(r?.status, 'needs-operator', JSON.stringify(r));
    assert.match(r?.detail ?? '', /halted[\s\S]*Requeue/);
    assert.equal(starts(fx), before, 'no re-entry');
    assert.ok(existsSync(queue(root, 'ready-for-review')), 'no claim');
    assert.ok(events(fx).some((e) => e.message === 'sendback.loop-halt-refused'), 'a named event');
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('CONTROL: a clean worktree re-enters and the round runs as today', async () => {
  const root = mkdtempSync(join(tmpdir(), 'drain-halt-control-'));
  try {
    const fx = plant(root, { dirty: false });
    const ran: string[] = [];
    const results = await drainPendingFixWorkItems({
      queueRoot: join(root, '_queue'), logsRoot: join(root, '_logs'), confirmMerge: () => false,
      phaseWiring: { ...UNREACHED_PHASE_WIRING, executor: { run: async (nodeId: string) => {
        ran.push(nodeId); // the fix WI builds: the round moves, so nothing halts whatever the later nodes do
        const wi6 = join(fx.worktree, '.forge', 'work-items', 'WI-6.md');
        writeFileSync(wi6, readFileSync(wi6, 'utf8').replace('status: pending', 'status: complete'));
        return 'ready-for-review';
      } } },
    });
    const r = results.find((x) => x.initiativeId === FIX_INIT);
    assert.ok(ran.length > 0, 'the rebase passed and a node ran');
    assert.equal(r?.status, 'drained', JSON.stringify(r));
    assert.equal(events(fx).some((e) => e.message === 'sendback.loop-halted'), false);
    assert.ok(events(fx).some((e) => e.message === 'sendback.loop-completed'), 'the round reads as completed, as today');
    assert.ok(existsSync(queue(root, 'ready-for-review')), 'the stranded-manifest return is unchanged');
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

